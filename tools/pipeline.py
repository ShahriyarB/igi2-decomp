"""Rebuild everything downstream of the retail IDB's function boundaries.

  types   regenerate include/igi2_types.h from the Final client PDB
  apply   fresh copy of the functions-only IDB, then names/types/globals/ABI/sanitize
  export  src/ tree and prototypes          data   globals and their original contents
  census  compile src/ and bucket the errors

usage: uv run pipeline.py [step ...]      (default: all, in order)
IDA steps run under the system Python that has idapro.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time

from config import REPO

STEPS = ["types", "apply", "export", "data", "census"]
SYSTEM_PY = "python"
SHARDS = 16


def run(cmd, **kw):
    print(">", " ".join(cmd), flush=True)
    t = time.time()
    subprocess.run(cmd, check=True, **kw)
    print(f"  ({time.time() - t:.0f}s)", flush=True)


def export(tools, retail):
    """Decompile in parallel: one idalib process per IDB copy, then merge their outputs."""
    shards = max(1, min(SHARDS, (os.cpu_count() or 2) - 2))
    shutil.rmtree(REPO / "src", ignore_errors=True)
    outdir = REPO / "build" / "export"
    shutil.rmtree(outdir, ignore_errors=True)
    copies = retail / "shards"
    # a shard killed mid-run leaves its database unpacked (shardK.id0/.id1/.nam/.til), and IDA
    # opens those instead of the fresh .i64 copied over: that shard then decompiled a stale IDB
    # in every later run (shard 11 printed calls with a type changed hours before)
    shutil.rmtree(copies, ignore_errors=True)
    copies.mkdir(exist_ok=True)
    procs = []
    t0 = time.time()
    for k in range(shards):
        idb = copies / f"shard{k}.i64"
        shutil.copyfile(retail / "igi2_1.0.exe.i64", idb)
        t_copy = time.time() - t0
        procs.append(subprocess.Popen([SYSTEM_PY, str(tools / "export.py"), "--idb", str(idb),
                                       "--shard", str(k), "--of", str(shards)],
                                      stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True))
    print(f"> export: {shards} shards", flush=True)
    failed = 0
    for p in procs:
        out, _ = p.communicate()
        print("  " + (out.strip().splitlines() or ["(no output)"])[-1], flush=True)
        failed += p.returncode != 0
    if failed:
        raise SystemExit(f"{failed} export shards failed")
    status, protos = {}, {}
    for k in range(shards):
        status.update(json.loads((outdir / f"status_{k}.json").read_text()))
        protos.update(json.loads((outdir / f"protos_{k}.json").read_text()))
    (REPO / "build" / "export_status.json").write_text(json.dumps(status, indent=1))
    hdr = ["/* Generated by tools/export.py -- do not edit. */", "#pragma once", '#include "igi2_types.h"', ""]
    (REPO / "include" / "igi2_protos.h").write_text("\n".join(hdr + [protos[n] for n in sorted(protos)]) + "\n")
    print(f"  merged: {len(status)} functions ({time.time() - t0:.0f}s, copies {t_copy:.0f}s)", flush=True)


# everything ida_apply.py reads (its default steps): with all of it unchanged, its result is too
APPLY_INPUTS = ["work/retail/igi2_1.0.exe.functions.i64", "tools/ida_apply.py", "include/igi2_types.h",
                "overrides/ida_types.json", "symbols/final.json", "symbols/match.json",
                "symbols/data_match.json", "symbols/abi.json", "build/abi_hints.json",
                "build/scoped_names.json", "build/system_idents.json", "build/system_protos.json"]


def inputs_digest(paths):
    h = hashlib.sha1()
    for rel in paths:
        path = REPO / rel
        h.update(rel.encode() + b"\0" + (path.read_bytes() if path.exists() else b"(missing)") + b"\0")
    return h.hexdigest()


def main():
    steps = sys.argv[1:] or STEPS
    tools = REPO / "tools"
    retail = REPO / "work" / "retail"
    for step in STEPS:
        if step not in steps:
            continue
        if step == "types":
            run(["uv", "run", "-q", "gen_types.py"], cwd=tools)
        elif step == "apply":
            if (REPO / "src").exists():  # callbacks the last export still names by address
                run([SYSTEM_PY, str(tools / "ida_define_referenced.py")])
            key, key_file = inputs_digest(APPLY_INPUTS), REPO / "build" / "apply_inputs.sha1"
            applied = retail / "igi2_1.0.exe.applied.i64"
            if applied.exists() and key_file.exists() and key_file.read_text() == key:
                print("> apply: inputs unchanged, reusing the applied IDB", flush=True)
                shutil.copyfile(applied, retail / "igi2_1.0.exe.i64")
            else:
                key_file.unlink(missing_ok=True)
                shutil.copyfile(retail / "igi2_1.0.exe.functions.i64", retail / "igi2_1.0.exe.i64")
                run([SYSTEM_PY, str(tools / "ida_apply.py")])
                shutil.copyfile(retail / "igi2_1.0.exe.i64", applied)
                key_file.write_text(key)
        elif step == "export":
            # from the applied IDB every time: "settle" saves decompiled signatures into the IDB,
            # and on top of a previous run's it kept a type the apply had since corrected (it
            # decompiles with the stale one and stores it again)
            applied = retail / "igi2_1.0.exe.applied.i64"
            if applied.exists():
                shutil.copyfile(applied, retail / "igi2_1.0.exe.i64")
            # pass 1 measures every function's decompiled signature; "settle" stores them so
            # pass 2 prints call sites that agree with the definitions
            export(tools, retail)
            for _ in range(2):  # signatures settle over two rounds (fixing one function frees others)
                run([SYSTEM_PY, str(tools / "ida_apply.py"), "settle", "sanitize"])
                export(tools, retail)
        elif step == "data":
            run([SYSTEM_PY, str(tools / "export_data.py")])
            run([SYSTEM_PY, str(tools / "ida_fallback.py")])  # the retail fallback's table
        elif step == "census":
            run(["uv", "run", "-q", "census.py"], cwd=tools)


if __name__ == "__main__":
    main()
