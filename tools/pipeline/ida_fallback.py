"""Generate data/fallback_gen.c: for every decompiled function, where its retail original takes
each argument (register, or offset on the stack), so runtime/fallback.c can run the retail code
in its place; and the retail C runtime routines that keep state, to send to ours.

The C function is cdecl with every argument on the stack, in the order of the IDA type the
export printed it from; the retail one takes them where that type says (LTCG registers, stack
offsets). A function the table cannot describe exactly (varargs, a register pair, ebp/esp, an
argument count that differs from the C prototype) is left out and listed.

usage: python tools/pipeline/ida_fallback.py     (system Python with idapro; after export and data)
"""
import json
import re
from pathlib import Path

import idapro

REPO = Path(__file__).resolve().parents[2]
IDB = REPO / "work" / "retail" / "igi2_1.0.exe.i64"
if idapro.open_database(str(IDB), run_auto_analysis=False):
    raise SystemExit(f"could not open {IDB}")

import ida_funcs  # noqa: E402
import ida_idp  # noqa: E402
import ida_nalt  # noqa: E402
import ida_typeinf  # noqa: E402
import idautils  # noqa: E402
import idc  # noqa: E402

REGS = {"eax": 0, "ecx": 1, "edx": 2, "ebx": 3, "esi": 4, "edi": 5}

# retail runtime routines with state of their own (heap, files, locale, rand, errno, exit):
# retail code calls ours for these. Pure ones (strlen, memcpy, floor, _ftol, _chkstk...) stay.
STATEFUL = """
malloc free realloc calloc _msize _expand _heapmin
fopen fclose fread fwrite fseek ftell feof ferror fflush fgets fputs fgetc fputc getc putc ungetc
fprintf vfprintf printf vprintf sprintf vsprintf _snprintf _vsnprintf sscanf fscanf _fsopen
remove rename _unlink _access _mkdir _rmdir _chdir _getcwd _findfirst _findnext _findclose _stat _fstat
_open _close _read _write _lseek _filelength _fileno _setmode _commit
rand srand time _time64 clock _ftime localtime gmtime mktime _strtime _strdate
atexit exit _exit abort _errno getenv _putenv
_strlwr _strupr _stricmp _strnicmp _strcmpi tolower toupper _tolower _toupper strtok
atoi atol atof strtol strtoul strtod _itoa _ltoa _ultoa
_beginthread _beginthreadex _endthread
""".split()

status = json.loads((REPO / "build" / "export_status.json").read_text())
protos = (REPO / "include" / "generated" / "igi2_protos.h").read_text()


def c_param_count(name):
    m = re.search(rf"\b{re.escape(name)}\((?P<args>[^;]*)\);", protos)
    if not m:
        return None
    args = m.group("args").strip()
    if args in ("", "void"):
        return 0
    depth, n = 0, 1
    for ch in args:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif ch == "," and depth == 0:
            n += 1
    return n


def describe(name, ea):
    """[(isReg, reg, size, ours, retail)], retail stack bytes; or a reason it cannot be"""
    tif = ida_typeinf.tinfo_t()
    if not ida_nalt.get_tinfo(tif, ea) or not tif.is_func():
        return None, "no type"
    fi = ida_typeinf.func_type_data_t()
    if not tif.get_func_details(fi):
        return None, "no details"
    if fi.is_vararg_cc() or fi.get_cc() == ida_typeinf.CM_CC_ELLIPSIS:
        return None, "varargs"
    args = []
    for a in fi:
        size = a.type.get_size()
        if size in (0, ida_typeinf.BADSIZE):
            return None, f"size of {a.name}"
        loc = a.argloc
        if loc.is_reg1():
            reg = ida_idp.get_reg_name(loc.reg1(), 4)
            if reg not in REGS or size > 4:
                return None, f"register {reg} for {a.name}"
            args.append([1, REGS[reg], size, 0, 0])
        elif loc.is_stkoff():
            args.append([0, 0, size, 0, loc.stkoff()])
        else:
            return None, f"location of {a.name}"
    count = c_param_count(name)
    if count == len(args) + 1 and all(a[0] or a[4] >= 4 for a in args):
        args.insert(0, [0, 0, 4, 0, 0])  # the hidden struct-return pointer the C passes first
    elif count != len(args):
        return None, f"C has {count} parameters, the type {len(args)}"
    ours = 0
    for a in args:
        a[3] = ours
        ours += (a[2] + 3) & ~3
    stack = max([a[4] + ((a[2] + 3) & ~3) for a in args if not a[0]] or [0])
    return args, stack


def purge_and_return(ea):
    """(bytes the retail function pops itself, how it returns: 0 nothing, 1 eax, 2 edx:eax, 3 st0)"""
    tif = ida_typeinf.tinfo_t()
    fi = ida_typeinf.func_type_data_t()
    if not ida_nalt.get_tinfo(tif, ea) or not tif.get_func_details(fi):
        return 0, 1
    purge = tif.calc_purged_bytes()
    purge = purge if purge not in (None, ida_typeinf.BADSIZE) and purge > 0 else 0
    rt = fi.rettype
    if rt.is_void():
        ret = 0
    elif rt.is_floating():
        ret = 3
    elif rt.get_size() == 8:
        ret = 2
    else:
        ret = 1  # a struct returned through a hidden pointer returns that pointer in eax
    return purge, ret


lines = ["/* Generated by tools/pipeline/ida_fallback.py -- do not edit. */", '#include "igi2.h"',
         '#include "fallback.h"', ""]
rows, skipped = [], []
for name, st in sorted(status.items()):
    if st["state"] not in ("decompiled", "override") or not st["file"].endswith(".c"):
        continue
    args, stack = describe(name, st["ea"])
    if args is None:
        skipped.append(f"{name}: {stack}")
        continue
    if args:
        body = ", ".join(f"{{{a[0]}, {a[1]}, {a[2]}, {a[3]}, {a[4]}}}" for a in args)
        lines.append(f"static const Igi2FallbackArg kArgs_{name}[] = {{ {body} }};")
    purge, ret = purge_and_return(st["ea"])
    rows.append(f'    {{ "{name}", "{st["file"]}", (void *){name}, {st["ea"]:#x}, {stack}, {len(args)}, '
                f'{f"kArgs_{name}" if args else "0"}, {purge}, {ret} }},')
lines += ["", "const Igi2FallbackFunc Igi2_atFallbackFunc[] = {", *rows, "};",
          f"const unsigned int Igi2_nFallbackFunc = {len(rows)};", ""]

# Functions that must stay C, even when retail code calls them: retail tests end of file inline
# ("test byte ptr [stream+0Ch], 10h", the old runtime's _IOEOF), and in today's runtime 0x10 is
# the error flag, so retail never saw end of file on our streams (the level graph parser read
# past it forever). The C reads feof() instead (rewrite.py), and retail callers reach it through
# the retail entry like any function not chosen.
described = {r.split('"')[1] for r in rows}
pinned = []
for name, st in sorted(status.items()):
    if st["state"] != "decompiled" or not st["file"].endswith(".c"):
        continue
    text = (REPO / "src" / st["file"]).read_text(encoding="utf-8", errors="replace")
    body = re.search(rf"^[^\s/#][^\n;]*\b{re.escape(name)}\((?:[^{{]*?)\)\s*\{{.*?^\}}", text, re.M | re.S)
    if not body or "feof(" not in body.group(0):
        continue
    if name not in described:
        skipped.append(f"{name}: tests end of file inline but is not in the table")
        continue
    pinned.append(name)
lines += ["/* never chosen: retail cannot run them against our runtime (see tools/pipeline/ida_fallback.py) */",
          "const char *const Igi2_azFallbackPinned[] = {", *[f'    "{n}",' for n in pinned], "    0", "};", ""]

# retail runtime routines, matched by C name. Not by the library flag: the library-name step
# left many unflagged (vfprintf, which devSTD_printf calls); game functions are excluded instead
game_eas = {v["ea"] for v in status.values()}
crt, seen = [], set()
for ea in idautils.Functions():
    f = ida_funcs.get_func(ea)
    if ea in game_eas:
        continue
    raw = idc.get_func_name(ea)
    c = raw[1:] if raw.startswith("_") else raw
    if c not in STATEFUL or c in seen:
        continue
    seen.add(c)
    crt.append(f'    {{ {ea:#x}, (void *){c}, "{c}" }},')

# the runtime's own allocation entries, which its library code (the D3DX the retail exe links
# statically) calls instead of malloc: the retail heap was never set up in this process
HEAP_INTERNALS = {"__nh_malloc": "malloc", "__heap_alloc": "malloc", "_malloc_crt": "malloc",
                  "??2@YAPAXI@Z": "malloc", "??_U@YAPAXI@Z": "malloc",
                  "??3@YAXPAX@Z": "free", "??_V@YAXPAX@Z": "free", "_free_crt": "free"}
# D3DX that allocates or talks to the device goes to the D3DX we link; its math stays retail
D3DX_PURE = ("D3DXMatrix", "D3DXVec", "D3DXQuaternion", "D3DXPlane", "D3DXColor")
d3dx_decls = []
# only the ones we can link: the SDK's d3dx8.lib (older than the one retail linked) and the
# stand-ins in runtime/libraries.c, by their decorated names
config = json.loads((REPO / "config.local.json").read_text())
linkable = set(re.findall(rb"_(D3DX\w+@\d+)", (Path(config["dx8_sdk"]) / "lib" / "d3dx8.lib").read_bytes()))
linkable = {x.decode() for x in linkable} | {"D3DXGetImageInfoFromFileInMemory@12", "D3DXSaveSurfaceToFileA@20"}
for ea in idautils.Functions():
    f = ida_funcs.get_func(ea)
    raw = idc.get_func_name(ea)
    if (raw.startswith("D3DX") and not raw.startswith(D3DX_PURE) and raw not in seen and f.argsize
            and f"{raw}@{f.argsize}" in linkable):
        # matched by name: the library-signature step left these unflagged
        seen.add(raw)
        d3dx_decls.append(f"int __stdcall {raw}({', '.join(['int'] * (f.argsize // 4))});")
        crt.append(f'    {{ {ea:#x}, (void *){raw}, "{raw}" }},')
        continue
    if ea in game_eas:
        continue
    if raw in HEAP_INTERNALS and raw not in seen:
        seen.add(raw)
        crt.append(f'    {{ {ea:#x}, (void *){HEAP_INTERNALS[raw]}, "{raw}" }},')

(REPO / "data" / "fallback_gen.c").write_text("\n".join(lines))
# its own file: the runtime's headers declare names the game also has (read, write, close), so
# it sees only them, and maps the guard heap's allocator itself, as decomp_defs.h does for the C
(REPO / "data" / "fallback_crt.c").write_text("\n".join([
    "/* Generated by tools/pipeline/ida_fallback.py -- do not edit. */",
    "#define _CRT_SECURE_NO_WARNINGS", "#define _CRT_NONSTDC_NO_DEPRECATE",
    "#include <stdio.h>", "#include <stdlib.h>", "#include <string.h>", "#include <ctype.h>",
    "#include <time.h>", "#include <io.h>", "#include <direct.h>", "#include <process.h>",
    "#include <sys/stat.h>", "#include <sys/timeb.h>", "#include <errno.h>", '#include "fallback.h"', "",
    "#ifdef IGI2_GUARD_HEAP", "void *igi2_guard_malloc(size_t n);", "void igi2_guard_free(void *p);",
    "void *igi2_guard_realloc(void *p, size_t n);", "#define malloc igi2_guard_malloc",
    "#define free igi2_guard_free", "#define realloc igi2_guard_realloc", "#endif", "",
    "/* the D3DX the game links (stdcall: declared with their retail argument size) */", *d3dx_decls, "",
    "const Igi2FallbackCrt Igi2_atFallbackCrt[] = {", *crt, "    { 0, 0, 0 }", "};",
    f"const unsigned int Igi2_nFallbackCrt = {len(crt)};", ""]))
(REPO / "build" / "fallback_skipped.txt").write_text("\n".join(skipped) + "\n")
print(f"fallback: {len(rows)} functions described, {len(skipped)} left out, {len(crt)} runtime routines")
idapro.close_database(save=False)
