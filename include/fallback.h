/* Retail fallback: run chosen functions as the original retail machine code instead of their
   decompiled C (support/fallback.c, table generated by tools/ida_fallback.py).

   The retail image sits at its own addresses in this process (data/data_init.c), code included,
   and shares every global with the C: a retail function can stand in for its C version. That
   makes a wrong function findable by bisection: send half of the suspects to retail, see whether
   the symptom goes, repeat. Chosen with IGI2_FALLBACK (see support/fallback.c).

   Both directions: the C entry of a chosen function goes to its retail code, and the retail entry
   of every other function goes to its C. Without the second, retail code reached retail code
   directly: a retail App_Open ran the whole retail start-up, and every handler it registered,
   whatever was chosen. */
#pragma once

/* where one argument of the C function (cdecl, all on the stack) goes for the retail one */
typedef struct {
    unsigned char isReg;      /* in a register (reg), else on the retail stack (retail) */
    unsigned char reg;        /* 0 eax 1 ecx 2 edx 3 ebx 4 esi 5 edi */
    unsigned short size;      /* bytes */
    unsigned short ours;      /* offset among the C function's stack arguments */
    unsigned short retail;    /* offset among the retail function's stack arguments */
} Igi2FallbackArg;

typedef struct {
    const char *zName;
    const char *zFile;        /* source file, for selecting a whole file */
    void *pOurs;              /* the C function */
    unsigned int retail;      /* its retail address */
    unsigned short nStack;    /* bytes of stack arguments the retail function takes */
    unsigned short nArgs;
    const Igi2FallbackArg *atArg;
    unsigned short nPurge;    /* bytes the retail function pops itself (0: its caller does) */
    unsigned char eReturn;    /* 0 nothing, 1 eax, 2 edx:eax, 3 st0 */
} Igi2FallbackFunc;

/* a retail C runtime routine that keeps state of its own (heap, files, locale, rand): retail
   code calls ours instead, so both halves share one heap and one set of files */
typedef struct {
    unsigned int retail;
    void *pOurs;
    const char *zName;
} Igi2FallbackCrt;

extern const Igi2FallbackFunc Igi2_atFallbackFunc[];
extern const unsigned int Igi2_nFallbackFunc;
extern const Igi2FallbackCrt Igi2_atFallbackCrt[];
extern const unsigned int Igi2_nFallbackCrt;
extern const char *const Igi2_azFallbackPinned[];  /* names, 0-terminated: retail entries jump to the C */
